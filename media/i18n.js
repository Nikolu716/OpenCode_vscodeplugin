  /** 从 VS Code / 浏览器语言代码映射到支持的 5 种语言 */
  function detect(lang) {
    const l = String(lang || "").toLowerCase().replace("_", "-")
    if (l === "zh-cn" || l === "zh" || l === "zh-hans") return "zh-cn"
    if (l === "zh-tw" || l === "zh-hk" || l === "zh-hant") return "zh-tw"
    if (l === "ko" || l === "ko-kr") return "ko"
    if (l === "ja" || l === "ja-jp") return "ja"
    return "en"
  }

  /** 取字符串，{name} 占位符替换 */
  function t(lang, key, params) {
    const dict = dicts[detect(lang)] || dicts.en
    let text = dict[key]
    if (text === undefined) text = dicts.en[key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll(`{${k}}`, String(v))
      }
    }
    return text
  }

  /** 所有语言的键集合（用于完整性测试） */
  function keys() {
    const base = Object.keys(dicts.en)
    return {
      base,
      languages: Object.keys(dicts),
      complete: Object.fromEntries(
        Object.entries(dicts).map(([lang, dict]) => [
          lang,
          base.filter((k) => dict[k] === undefined),
        ]),
      ),
    }
  }

  return { dicts, detect, t, keys }
